namespace Editor.Services.Dtos;

/// <summary>
/// RoastComment DTO
///
/// This is the data transfer object representing a single AI-generated
/// roast comment that will be displayed inline in the Monaco editor.
///
/// Each roast comment is bound to a specific line number and contains
/// the sarcastic feedback that will appear as an inline widget.
/// </summary>
public class RoastComment
{
    /// <summary>
    /// The line number (1-indexed) where this comment should appear.
    /// Line 1 is the first line of code.
    /// Line 5 means the comment appears after line 5.
    ///
    /// Example:
    ///   Line 1: public class User
    ///   Line 2: {
    ///   Line 3:     public string Email { get; set; }
    ///   Line 4: }
    ///   [ROAST COMMENT APPEARS HERE at LineNumber=3]
    /// </summary>
    public int LineNumber { get; set; }

    /// <summary>
    /// The actual roast comment text.
    /// This is the sarcastic feedback generated by the AI backend.
    ///
    /// Examples:
    /// - "Ah yes, storing passwords in plain text. Very 'secure'. 🔒"
    /// - "Wow, a 500-line function. Chess matches have shorter games."
    /// - "NULL checks? Where we're going, we don't need NULL checks."
    ///
    /// Can include:
    /// - Markdown formatting
    /// - Emoji
    /// - Code snippets
    /// - Multiple paragraphs
    /// </summary>
    public string CommentText { get; set; } = string.Empty;

    /// <summary>
    /// Optional: Thread ID for organizing comments.
    /// Useful if multiple comments can be on the same line.
    /// Can be used to group related discussions.
    /// </summary>
    public string? ThreadId { get; set; }

    /// <summary>
    /// Optional: Severity level of the roast.
    /// Could be: "Gentle", "Medium", "Brutal"
    /// Allows the UI to style comments differently based on intensity.
    /// </summary>
    public string Severity { get; set; } = "Medium";
}
