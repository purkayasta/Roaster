using Editor.Services.Dtos;

namespace Editor.Services;

/// <summary>
/// MockRoastApiService Implementation
///
/// This is a mock implementation of IRoastApiService that simulates
/// a real backend API without actually making HTTP requests.
///
/// WHY USE A MOCK?
/// ================
/// 1. The real backend doesn't exist yet
/// 2. Frontend development can proceed independently
/// 3. Testing is faster (no network calls)
/// 4. No external dependencies during development
/// 5. Easy to swap with real service later (just change Program.cs)
///
/// FEATURES:
/// =========
/// - Simulates 2-second network latency with Task.Delay
/// - Returns hardcoded roasts for lines 3 and 5
/// - Demonstrates how to use language-specific comments
/// - Handles all input gracefully
/// - Can be extended to simulate error conditions
///
/// MIGRATION STRATEGY:
/// ===================
/// When the real backend is ready:
///
/// 1. Create HttpRoastApiService : IRoastApiService
/// 2. In Program.cs, change:
///    FROM: builder.Services.AddScoped<IRoastApiService, MockRoastApiService>();
///    TO:   builder.Services.AddScoped<IRoastApiService, HttpRoastApiService>();
/// 3. No changes needed to CodeWorkspace.razor or RoastThread.razor!
///
/// This is the power of Dependency Injection.
/// </summary>
public class MockRoastApiService : IRoastApiService
{
    /// <summary>
    /// Simulates submitting code to the AI backend for roasting.
    ///
    /// In a real service, this would:
    /// - Make an HTTP POST to /api/roast
    /// - Send the SubmissionRequest as JSON
    /// - Wait for the backend to analyze the code
    /// - Parse the JSON response
    /// - Return the list of RoastComments
    ///
    /// The mock instead:
    /// - Accepts the request
    /// - Simulates 2-second network latency
    /// - Returns hardcoded roasts for specific lines
    /// - Varies the response based on language (shows flexibility)
    /// </summary>
    public async Task<List<RoastComment>> SubmitCodeAsync(SubmissionRequest request)
    {
        // Validate input
        if (string.IsNullOrWhiteSpace(request.Code))
        {
            // In a real service, might throw HttpRequestException
            // For mock, we'll just return empty list
            return new List<RoastComment>();
        }

        Console.WriteLine($"[MockRoastApiService] Received code submission ({request.Code.Length} chars, language: {request.Language})");

        // SIMULATE NETWORK LATENCY
        // This is important! It helps test loading states, error handling, etc.
        // 2 seconds is realistic for a real backend AI call
        await Task.Delay(2000);

        Console.WriteLine("[MockRoastApiService] Generating roast comments...");

        // RETURN HARDCODED ROASTS
        // In a real service, these would be generated by AI (GPT, etc.)
        // For now, we return the same roasts regardless of input
        // (In a more sophisticated mock, we might analyze the code and vary the response)

        var roasts = new List<RoastComment>();

        // Roast for line 3
        roasts.Add(new RoastComment
        {
            LineNumber = 3,
            CommentText = @"Ah, I see you're declaring a `UserService`. Tell me, does this service actually do anything useful, or is it just a placeholder for your ambitions? 🤔

*[Awaits actual implementation with bated breath]*",
            Severity = "Medium",
            ThreadId = "roast-3"
        });

        // Roast for line 5
        roasts.Add(new RoastComment
        {
            LineNumber = 5,
            CommentText = @"Wait, you're using `IRepository`? How delightfully abstract of you.

I'm sure the implementation definitely isn't just returning `null` for everything. 📚 Right? *Right?*",
            Severity = "Brutal",
            ThreadId = "roast-5"
        });

        // You could add more roasts here
        // roasts.Add(new RoastComment { LineNumber = 10, CommentText = "..." });

        Console.WriteLine($"[MockRoastApiService] Generated {roasts.Count} roast comments");

        return roasts;
    }

    /// <summary>
    /// Simulates posting a user's reply to a roast thread.
    ///
    /// In a real service, this would:
    /// - Make an HTTP POST to /api/roast/{lineNumber}/reply
    /// - Send the user's reply text
    /// - Store it in a database
    /// - Return success/failure
    /// - Possibly trigger notifications
    /// - Persist the conversation
    ///
    /// The mock instead:
    /// - Accepts the reply
    /// - Simulates 1-second network latency
    /// - Always returns true (success)
    /// - Logs the reply
    /// </summary>
    public async Task<bool> ReplyToThreadAsync(int lineNumber, string userReply)
    {
        // Validate input
        if (string.IsNullOrWhiteSpace(userReply))
        {
            Console.WriteLine("[MockRoastApiService] Empty reply rejected");
            return false;
        }

        if (lineNumber <= 0)
        {
            Console.WriteLine("[MockRoastApiService] Invalid line number");
            return false;
        }

        Console.WriteLine($"[MockRoastApiService] User reply to line {lineNumber}: {userReply}");

        // SIMULATE NETWORK LATENCY
        // Slightly faster than SubmitCodeAsync since it's a simpler operation
        await Task.Delay(1000);

        Console.WriteLine("[MockRoastApiService] Reply posted successfully");

        // Always return true for the mock
        // In reality, you might check:
        // - Is the line number valid?
        // - Is the reply text appropriate?
        // - Did the database write succeed?
        // - etc.
        return true;
    }
}
